#!/usr/bin/env python3
"""Makes rtl/karabas_mini_top.v and rtl/karabas_go_top.v from rtl/karabas_minig_top.v (link v2).

The three tops share the core logic; the board glue differs. Change the Mini G top, then run this
(every replacement must match exactly once, else it stops). The header comment, the port list and
the pin glue of Mini / Go are taken from git (the last v1 tops, ref V1_REF), the body from Mini G.

Mini (before rev.G): MCU_IO is 4 bits (INT on MCU_IO[1], as Mini G); no I2S DAC: kg_sigma_delta_dac
  on AUDIO_L / AUDIO_R; FT_RESET, MIDI_CLK / MIDI_RESET_N, ESP_RESET_N / ESP_BOOT_N held inactive.
Go: INT on MCU_IO[0] (N9, the burst ready line of v1); VGA 8:8:8 with V_CLK instead of HDMI; no
  FT_CLK_OUT; DAC_LRCK / DAC_MUTE; the floppy connector (paula_floppy_ext of nanomig: FLOPPY_EXT,
  IMG_PHYS, DSKCHG over FDD_CHNG, its debug words on AUX).
"""
import os
import subprocess
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RTL = os.path.join(SRC, "rtl")
V1_REF = "43a6fa6"  # the master of the v1 release (before link v2)


def sub(s, old, new, what):
    if s.count(old) != 1:
        sys.exit("mktops.py: %s: %d matches of %r" % (what, s.count(old), old[:70]))
    return s.replace(old, new)


def v1(board):
    return subprocess.check_output(["git", "show", "%s:src/rtl/karabas_%s_top.v" % (V1_REF, board)],
                                   cwd=SRC).decode()


def head(s):
    """the text up to the end of the port list"""
    i = s.index("module karabas_")
    return s[:s.index("\n);\n", i) + 4]


def body(s):
    i = s.index("module karabas_")
    return s[s.index("\n);\n", i) + 4:]


minig = open(os.path.join(RTL, "karabas_minig_top.v")).read()
b = body(minig)

# ---------------------------------------------------------------- Mini
m = b
m = sub(m, "assign ESP32_SPI_CS_N = 1'b1;\n",
        "assign ESP_RESET_N = 1'bz;\nassign ESP_BOOT_N = 1'bz;\n", "mini esp")
m = sub(m, "assign FT_SPI_MOSI = 1'b0;\n",
        "// FT812 not used; FT_RESET high as in the other cores that do not use it\n"
        "assign FT_SPI_MISO = 1'bz;\nassign FT_SPI_MOSI = 1'bz;\nassign FT_INT_N = 1'bz;\n"
        "assign FT_CLK = 1'bz;\nassign FT_RESET = 1'b1;\n", "mini ft")
m = sub(m, "assign MIDI_TX = 1'b1;\n",
        "assign MIDI_TX = 1'b1;\nassign MIDI_CLK = 1'b1;\nassign MIDI_RESET_N = 1'b1;\n", "mini midi")
m = sub(m, "assign MCU_IO[5:2] = 4'bzzzz;", "assign MCU_IO[3:2] = 2'bzz;", "mini mcu_io")
m = sub(m, """kg_pcm5102 #(.DIV_BITS(2)) pcm5102(
	.clk(clk_sys),
	.reset(areset),
	.left(audio_l),
	.right(audio_r),
	.din(DAC_DAT),
	.bck(DAC_BCK),
	.lrck(DAC_WS)
);""", """// Mini has no I2S DAC: sigma-delta outputs into an RC filter, offset binary input
kg_sigma_delta_dac dac_l(.clk(clk_sys), .reset(areset), .din({ ~audio_l[15], audio_l[14:0] }), .dout(AUDIO_L));
kg_sigma_delta_dac dac_r(.clk(clk_sys), .reset(areset), .din({ ~audio_r[15], audio_r[14:0] }), .dout(AUDIO_R));""",
        "mini dac")
mini = head(v1("mini")).replace("[0] burst cs_n, [1] burst ready, [2] sd2 cs_n, [3] ft cs_n",
                                "[1] INT of link v2, [2] sd2 cs_n, [3] ft cs_n")
mini += ("// karabas: generated by src/tools/mktops.py from karabas_minig_top.v (do not edit: change that one\n"
         "// and run it): the same except the pins, the sigma-delta audio and MCU_IO of 4 bits\n") + m

# ---------------------------------------------------------------- Go
g = b
g = sub(g, "assign ADC_CLK = 1'b0;\nassign ADC_BCK = 1'b0;\nassign ADC_LRCK = 1'b0;\n",
        "assign BEEPER = 1'b0;\n", "go adc")
g = sub(g, "assign ESP32_SPI_CS_N = 1'b1;\n", """assign ESP_RESET_N = 1'bz;
assign ESP_BOOT_N = 1'bz;

// the floppy connector (paula_floppy_ext of nanomig)
wire [7:0] fdd_out;            // { wdata, wgate, side1, step, dir, motor, ds1, ds0 }
assign FDC_DRIVE = fdd_out[1:0];
assign FDC_MOTOR = fdd_out[2];
assign FDC_DIR = fdd_out[3];
assign FDC_STEP = fdd_out[4];
assign FDC_SIDE_N = fdd_out[5];
assign FDC_WGATE = fdd_out[6];
assign FDC_WDATA = fdd_out[7];
""", "go esp")
g = sub(g, "assign FT_SPI_MOSI = 1'b0;\n",
        "assign FT_SPI_MISO = 1'bz;\nassign FT_SPI_MOSI = 1'bz;\nassign FT_INT_N = 1'bz;\n"
        "assign FT_CLK = 1'bz;\nassign FT_OE_N = 1'b1;\n", "go ft")
g = sub(g, "assign MIDI_TX = 1'b1;\n",
        "assign MIDI_TX = 1'b1;\nassign MIDI_CLK = 1'b1;\nassign MIDI_RESET_N = 1'b1;\n", "go midi")
# no FT_CLK_OUT pin on Go
g = sub(g, """
// the clock of the FT812: it must always have one (karabas-go-notes ft-clk-out-required)
wire clk_8;
BUFG u_clk_8 (.I(clkout1), .O(clk_8));
ODDR2 u_ft_clk (.Q(FT_CLK_OUT), .C0(clk_8), .C1(~clk_8), .CE(1'b1), .D0(1'b1), .D1(1'b0), .R(1'b0), .S(1'b0));
""", "\n// Go has no FT_CLK_OUT: CLKOUT1 of the PLL is not used\n", "go ft clk")
g = sub(g, """wire mcu_int;
assign MCU_IO[1] = mcu_int;
assign MCU_IO[0] = 1'bz;
assign MCU_IO[5:2] = 4'bzzzz;""", """// Go: INT on MCU_IO[0] (N9, the burst ready line of v1, MCU_SPI_IO[0] of the firmware docs)
wire mcu_int;
assign MCU_IO[0] = mcu_int;
assign MCU_IO[1] = 1'bz;
assign MCU_IO[3:2] = 2'bzz;

wire img_phys_wr;
wire [2:0] fdd_chng_req;       // { one clock, drive 1 DS0 / 2 DS1 }
wire fdd_chng_wr;
wire [15:0] fdd_chng;          // { drive, value }
wire [31:0] fdd_dbg;           // paula_floppy_ext state (DEBUG_ADDR / DEBUG_DATA)
wire [15:0] img_phys;""", "go mcu_io")
g = sub(g, "	.IMG_WP(), .IMG_PHYS_WR(), .IMG_PHYS(), .IMG_FLUSH(), .FDD_CHNG_WR(), .FDD_CHNG(),\n"
        "	.FDD_CHNG_REQ(1'b0), .FDD_CHNG_DS(2'd0),",
        "	.IMG_WP(), .IMG_PHYS_WR(img_phys_wr), .IMG_PHYS(img_phys), .IMG_FLUSH(),\n"
        "	.FDD_CHNG_WR(fdd_chng_wr), .FDD_CHNG(fdd_chng),\n"
        "	.FDD_CHNG_REQ(fdd_chng_req[2]), .FDD_CHNG_DS(fdd_chng_req[1:0]),", "go img")
g = sub(g, ".DEBUG_ADDR(16'd0), .DEBUG_DATA(16'd0),",
        ".DEBUG_ADDR(fdd_dbg[31:16]), .DEBUG_DATA(fdd_dbg[15:0]),", "go debug")
g = sub(g, """reg [3:1] df_img = 3'b000;""", """reg [7:0] floppy_ext = 8'd0;   // DFn: [2n+1:2n] = 0 image, 1 DS0, 2 DS1
reg [3:0] floppy_ext_chg = 4'd0;
always @(posedge clk_sys) begin : floppy_ext_blk
	integer n;
	floppy_ext_chg <= 4'd0;
	for (n = 0; n < 4; n = n + 1) begin
		if (sdc_img_mounted[n])
			floppy_ext[2*n +: 2] <= 2'd0;
		if (img_phys_wr && img_phys[15:8] == n) begin
			floppy_ext[2*n +: 2] <= (img_phys[1:0] == 2'd3) ? 2'd0 : img_phys[1:0];
			floppy_ext_chg[n] <= 1'b1;
		end
	end
end
wire [3:0] df_ext = { floppy_ext[7:6] != 2'd0, floppy_ext[5:4] != 2'd0, floppy_ext[3:2] != 2'd0, floppy_ext[1:0] != 2'd0 };

reg [3:1] df_img = 3'b000;""", "go floppy_ext")
g = sub(g, "reg [1:0] drives = 2'd0;       // drives - 1\n",
        "reg [1:0] drives = 2'd0;       // drives - 1\nwire [3:1] df_on = df_img | df_ext[3:1];\n", "go df_on")
g = sub(g, "drives <= df_img[3] ? 2'd3 : df_img[2] ? 2'd2 : df_img[1] ? 2'd1 : 2'd0;",
        "drives <= df_on[3] ? 2'd3 : df_on[2] ? 2'd2 : df_on[1] ? 2'd1 : 2'd0;", "go drives")
g = sub(g, "nanomig nanomig(", "nanomig #(.FLOPPY_EXT(1)) nanomig(", "go nanomig")
g = sub(g, """	.floppy_ext(8'd0),             // no floppy connector
	.floppy_ext_chg(4'd0),
	.fdd_in(4'd0),
	.fdd_out(),
	.fdd_chng_req(),
	.fdd_chng_in(5'd0),
	.fdd_dbg(),""", """	.floppy_ext(floppy_ext),
	.floppy_ext_chg(floppy_ext_chg),
	.fdd_in({ FDC_RDATA, FDC_WPRT, FDC_TR00, FDC_INDEX }),
	.fdd_out(fdd_out),
	.fdd_chng_req(fdd_chng_req),
	.fdd_chng_in({ fdd_chng_wr, fdd_chng[9:8], fdd_chng[1:0] }),
	.fdd_dbg(fdd_dbg),""", "go fdd")
i = g.index("zhdmi_top #(.SAMPLERATE(48000)) zhdmi_top(")
j = g.index(");", i) + 2
g = g[:i] + """// VGA through the video DAC (no HDMI on Go): the OSD output registered once more
reg [23:0] vga_rgb = 24'h000000;
reg vga_hs = 1'b1, vga_vs = 1'b1;
always @(posedge clk_sys) begin
	vga_rgb <= osd_rgb;
	vga_hs <= osd_hs;
	vga_vs <= osd_vs;
end

assign VGA_R = vga_rgb[23:16];
assign VGA_G = vga_rgb[15:8];
assign VGA_B = vga_rgb[7:0];
assign VGA_HS = vga_hs;
assign VGA_VS = vga_vs;

// pixel clock of the VGA DAC
ODDR2 u_v_clk (.Q(V_CLK), .C0(clk_sys), .C1(~clk_sys), .CE(1'b1), .D0(1'b1), .D1(1'b0), .R(1'b0), .S(1'b0));

// dvi_only (mcu) has no use without hdmi""" + g[j:]
g = sub(g, """	.lrck(DAC_WS)
);""", """	.lrck(DAC_LRCK)
);
assign DAC_MUTE = 1'b1; // soft mute: 0 = mute, 1 = play""", "go dac")
go = head(v1("go")).replace("[0] burst ready (N9), [1] burst cs_n (M11), [2] sd2 cs_n, [3] ft cs_n",
                            "[0] INT of link v2 (N9), [2] sd2 cs_n, [3] ft cs_n")
go += ("// karabas: generated by src/tools/mktops.py from karabas_minig_top.v (do not edit: change that one\n"
       "// and run it): the same except the pins, VGA instead of HDMI and the floppy connector\n") + g

open(os.path.join(RTL, "karabas_mini_top.v"), "w").write(mini)
open(os.path.join(RTL, "karabas_go_top.v"), "w").write(go)
print("mktops.py: karabas_mini_top.v, karabas_go_top.v")
